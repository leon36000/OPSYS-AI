_VALID_CODES = set(_VERDICTS.keys())


def est_verdict(code: str) -> bool:
    """Vérifie si le code appartient au catalogue des verdicts."""
    return code in _VALID_CODES


def construire_verdict(code: str, statut: str = "", detail: str | None = None) -> dict:
    """Retourne un verdict structuré {code, statut, detail}."""
    if not est_verdict(code):
        raise ValueError(f"Code verdict inconnu: {code}")
    return {"code": code, "statut": statut, "detail": detail or ""}
