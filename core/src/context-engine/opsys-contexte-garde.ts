// `before_tool_call` guard of the OPSYS context engine (OPSYS-AI PLAN T3.3-suite-b, ADR-0010 decision 4).
//
// An agent must not act on the enterprise without knowing the state of the case. For an OPSYS tool of
// level N3 or more, the call is BLOCKED when, in this session's current turn,
//   - the case's packet was unavailable (engine unreachable, too slow, invalid or oversized packet, no
//     case, or a session that no human linked to a case), or was never evaluated, or is stale; or
//   - the packet holds a critical signal that is still OPEN (nobody took note of it).
// The message says what to do: have a human take note of the signal, or retry once the context is
// available. Nothing else is ever blocked: a tool of level N0 to N2, a tool that is not an OPSYS tool of
// the generated configuration, an agent the configuration does not name.
//
// The level of a tool comes from `contexte.json` (`niveaux`, generated by `openclaw.py` from the
// manifests), never from the model. The open-signal count is M10's, over every signal of the case: a
// truncated layer cannot hide one (`opsys-contexte-paquet.ts`).
//
// OFF when `contexte.json` is absent or explicitly inactive. Once the operator selects this engine,
// an invalid configuration blocks OPSYS-shaped calls because the levels cannot be trusted.
//
// How the state gets here. The engine writes it in `assemble()` (`OpsysContextEngine`), once per turn,
// under the session key. This module only reads it. A context engine cannot itself veto a tool call:
// `before_tool_call` belongs to the plugin hook runner and to trusted tool policies (both registered by
// plugins), and a `ContextEngine` has no such method. So the veto is a call to `checkOpsysContexteToolCall`
// from `runBeforeToolCallHook` (`src/agents/agent-tools.before-tool-call.policy.ts`); see the graft
// documented in `core/PROVENANCE.md` and ADR-0010. Until that graft is in, this module decides and the
// core does not enforce.
import { normalizeAgentId } from "@openclaw/normalization-core/agent-id";
import { isRecord } from "@openclaw/normalization-core/record-coerce";
import { parseAgentSessionKey } from "../routing/session-key.js";
import {
  OPSYS_TOOL_LEVELS,
  readOpsysContexteConfig,
  type OpsysContexteConfigResult,
  type OpsysToolLevel,
} from "./opsys-contexte-config.js";
import { isOpsysAffaireId, oneLine } from "./opsys-contexte-paquet.js";

/** What the last turn's PREFLIGHT found out about the case. */
export type OpsysGuardState =
  | { kind: "ready"; affaireId: string; nbOuverts: number; atMs: number }
  | { kind: "unavailable"; reason: string; atMs: number };

export type OpsysGuardDecision = { block: false } | { block: true; reason: string };

/** A state older than this is not trusted: the next turn assembles a fresh one. */
export const OPSYS_GUARD_MAX_AGE_MS = 15 * 60 * 1_000;
// Sessions kept at once. Oldest evicted first: an evicted session is simply "not evaluated" (blocked).
const MAX_SESSIONS = 512;
const TOOL_NAME_SEPARATOR = "__";
// The shape of every OPSYS tool name (`opsys.outils.Outil`): a department code or `opsys`, then `_`.
const OPSYS_TOOL_NAME = /^(?:m(?:10|[1-9])|opsys)_[a-z][a-z0-9_]{1,60}$/u;
const MIN_GUARDED_RANK = OPSYS_TOOL_LEVELS.indexOf("N3");

/** The last packet state of each session, bounded. Written by the engine, read by the guard. */
export class OpsysContexteGuardStore {
  private readonly states = new Map<string, OpsysGuardState>();

  set(sessionKey: string, state: OpsysGuardState): void {
    // Re-insert so the map's order is the order of the last write.
    this.states.delete(sessionKey);
    this.states.set(sessionKey, state);
    while (this.states.size > MAX_SESSIONS) {
      const oldest = this.states.keys().next();
      if (oldest.done === true) {
        break;
      }
      this.states.delete(oldest.value);
    }
  }

  get(sessionKey: string): OpsysGuardState | undefined {
    return this.states.get(sessionKey);
  }

  clear(): void {
    this.states.clear();
  }

  get size(): number {
    return this.states.size;
  }
}

/** The store the engine and the graft share in production. Tests pass their own. */
export const opsysContexteGuardStore = new OpsysContexteGuardStore();

/** Model-facing tool names are `<server>__<tool>` (`agent-bundle-mcp-names.ts`): the level is looked up by bare name. */
function bareToolName(toolName: string): string {
  const at = toolName.lastIndexOf(TOOL_NAME_SEPARATOR);
  return at === -1 ? toolName : toolName.slice(at + TOOL_NAME_SEPARATOR.length);
}

function isGuardedLevel(level: OpsysToolLevel): boolean {
  return OPSYS_TOOL_LEVELS.indexOf(level) >= MIN_GUARDED_RANK;
}

function agentIdOf(sessionKey: string | undefined, agentId: string | undefined): string | undefined {
  if (agentId !== undefined && agentId !== "") {
    return normalizeAgentId(agentId);
  }
  const parsed = parseAgentSessionKey(sessionKey);
  return parsed?.agentId ? normalizeAgentId(parsed.agentId) : undefined;
}

function blockedForContext(reason: string): OpsysGuardDecision {
  return {
    block: true,
    reason:
      `Action bloquée : le contexte d'entreprise de cette affaire est indisponible (${oneLine(reason)}). ` +
      "Réessaie quand il est disponible (au prochain tour). Ne contourne pas ce blocage : si l'action " +
      "est urgente, dis à l'humain qu'elle est bloquée faute de contexte.",
  };
}

function blockedForSignals(affaireId: string, nbOuverts: number): OpsysGuardDecision {
  return {
    block: true,
    reason:
      `Action bloquée : ${String(nbOuverts)} signal(aux) critique(s) OUVERT(S) sur l'affaire ${oneLine(affaireId)}, ` +
      "dont personne n'a pris connaissance. Dis à l'humain de le lire et d'en prendre connaissance (app admin, " +
      "ou approbation de m10_prendre_en_compte_signal dans la console OPSYS), puis réessaie. " +
      "Tu ne peux pas le faire à sa place.",
  };
}

function blockedForTarget(reason: string): OpsysGuardDecision {
  return {
    block: true,
    reason:
      `Action bloquée : la cible de l'outil ne correspond pas à l'affaire M10 évaluée (${oneLine(reason)}). ` +
      "Précise l'affaire visée et fais lire son contexte avant de réessayer.",
  };
}

function valueAtPath(value: unknown, path: readonly string[]): unknown {
  let current: unknown = value;
  for (const segment of path) {
    if (!isRecord(current)) {
      return undefined;
    }
    if (!Object.hasOwn(current, segment)) {
      return undefined;
    }
    current = current[segment];
  }
  return current;
}

const LEAD_ID = /^[A-Za-z0-9][A-Za-z0-9._:-]{0,63}$/u;
const WCT_ID = /^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$/u;

function targetMatches(
  target: unknown,
  identity: "affaire" | "lead" | "wct",
  affaireId: string,
): boolean {
  if (typeof target !== "string" || !isOpsysAffaireId(affaireId)) {
    return false;
  }
  if (identity === "affaire") {
    return isOpsysAffaireId(target) && target === affaireId;
  }
  if (identity === "lead") {
    // A lead-scoped action is valid only for the canonical lead case itself. A matching lead
    // prefix does not authorize an opportunity for another WCT.
    return LEAD_ID.test(target) && target === affaireId;
  }
  return WCT_ID.test(target) && affaireId.endsWith(`~opp~${target}`);
}

/**
 * The decision, as a pure function of what the engine recorded. `config` is what `readOpsysContexteConfig`
 * returned; `state` is the session's last recorded state, if any.
 */
export function evaluateGuard(params: {
  toolName: string;
  sessionKey: string | undefined;
  agentId: string | undefined;
  config: OpsysContexteConfigResult;
  state: OpsysGuardState | undefined;
  toolParams: unknown;
  nowMs: number;
}): OpsysGuardDecision {
  if (params.config.kind === "absent" || params.config.kind === "disabled") {
    return { block: false };
  }
  // The operator selected this engine, but a broken configuration cannot tell us which OPSYS
  // tools are N3+. Fail closed for OPSYS-shaped calls and preserve unrelated tools.
  if (params.config.kind === "invalid") {
    return OPSYS_TOOL_NAME.test(bareToolName(params.toolName))
      ? blockedForContext(`configuration de contexte invalide : ${params.config.reason}`)
      : { block: false };
  }
  const { config } = params.config;
  const agentId = agentIdOf(params.sessionKey, params.agentId);
  if (agentId === undefined || !config.agents.has(agentId)) {
    return { block: false };
  }
  const level = config.levels.get(bareToolName(params.toolName));
  if (level === undefined || !isGuardedLevel(level)) {
    return { block: false };
  }
  const { state } = params;
  if (state === undefined || params.nowMs - state.atMs > OPSYS_GUARD_MAX_AGE_MS) {
    return blockedForContext("le contexte n'a pas été évalué pour ce tour, ou son évaluation est périmée");
  }
  if (state.kind === "unavailable") {
    return blockedForContext(state.reason);
  }
  const target = config.targets.get(bareToolName(params.toolName));
  if (target === undefined || target.kind === "unknown") {
    return blockedForTarget(
      `aucun contrat de cible fiable n'est déclaré pour ${bareToolName(params.toolName)}; le propriétaire doit déclarer affaire ou globale`,
    );
  }
  if (
    target.kind === "affaire" &&
    !targetMatches(valueAtPath(params.toolParams, target.path), target.identity, state.affaireId)
  ) {
    return blockedForTarget(
      `l'argument ${target.path.join(".")} est absent, invalide ou vise une autre affaire que ${state.affaireId}`,
    );
  }
  return state.nbOuverts > 0 ? blockedForSignals(state.affaireId, state.nbOuverts) : { block: false };
}

/** Seams for tests. Production passes none of them. */
export type OpsysGuardDeps = {
  readConfig?: () => OpsysContexteConfigResult;
  store?: OpsysContexteGuardStore;
  nowMs?: () => number;
};

/**
 * The single entry point of the `before_tool_call` graft: reads the configuration and the session's
 * recorded state and decides. Never throws. If the guard itself fails it cannot know the tool's level,
 * so it blocks what has the shape of an OPSYS tool name and lets every other tool through: a bug here
 * must not become a hole for OPSYS actions, nor stop the agent's own tools.
 */
export function checkOpsysContexteToolCall(
  params: { toolName: string; sessionKey: string | undefined; agentId: string | undefined; toolParams?: unknown },
  deps: OpsysGuardDeps = {},
): OpsysGuardDecision {
  try {
    const config = (deps.readConfig ?? (() => readOpsysContexteConfig()))();
    const store = deps.store ?? opsysContexteGuardStore;
    const state = params.sessionKey === undefined ? undefined : store.get(params.sessionKey);
    return evaluateGuard({
      ...params,
      toolParams: params.toolParams,
      config,
      state,
      nowMs: (deps.nowMs ?? Date.now)(),
    });
  } catch {
    return OPSYS_TOOL_NAME.test(bareToolName(params.toolName))
      ? blockedForContext("le garde du moteur de contexte a échoué")
      : { block: false };
  }
}
